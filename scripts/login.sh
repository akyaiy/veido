#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

SERVER_URL="http://localhost:8080"
SESSION_FILE=".site-session"
USERNAME=""
PASSWORD=""

usage() {
  cat <<'EOF'
Usage: scripts/login.sh --username USER [--password PASSWORD]

Authenticates through auth.login and saves the access JWT in .site-session
(mode 600 by default). Password is never written to disk.
EOF
}

while (($#)); do
  case "$1" in
    --server) SERVER_URL="$2"; shift 2 ;;
    --session-file) SESSION_FILE="$2"; shift 2 ;;
    --username) USERNAME="$2"; shift 2 ;;
    --password) PASSWORD="$2"; shift 2 ;;
    -h|--help) usage; exit 0 ;;
    *) printf 'unknown argument: %s\n' "$1" >&2; usage >&2; exit 2 ;;
  esac
done

require_command() { command -v "$1" >/dev/null || { printf 'missing command: %s\n' "$1" >&2; exit 1; }; }
require_command curl
require_command jq
[[ -n "$USERNAME" ]] || { usage >&2; exit 2; }
if [[ -z "$PASSWORD" ]]; then
  read -r -s -p "Password for ${USERNAME}: " PASSWORD
  printf '\n' >&2
fi

payload="$(jq -cn --arg username "$USERNAME" --arg password "$PASSWORD" '{input:{username:$username,password:$password}}')"
response="$(curl -fsS "$SERVER_URL/api/v2/vfs/hooks/auth.login/run" -H 'Content-Type: application/json' --data "$payload")"
token="$(jq -er '.output.access_token' <<<"$response")"
resolved_user="$(jq -er '.output.username' <<<"$response")"

umask 077
cat >"$SESSION_FILE" <<EOF
# Generated by scripts/login.sh. Do not commit this file.
SITE_ACCESS_TOKEN=$(printf '%q' "$token")
SITE_SERVER_URL=$(printf '%q' "${SERVER_URL%/}")
export SITE_ACCESS_TOKEN SITE_SERVER_URL
EOF
chmod 600 "$SESSION_FILE"

printf 'Logged in as %s. Run: source %s\n' "$resolved_user" "$SESSION_FILE"
